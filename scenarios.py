"""
What your test runs. ← UNIT 8, MILESTONE 3

Each of your five criteria needs something run against it. A criterion about
false positives needs your own writing. One about label coverage needs inputs
across the score range. One about the appeal path needs a real content_id.

Working that out is Milestone 3's first step, and this file is where you write
it down. `run_eval.py` runs everything here three times.

Two are filled in as examples. Replace them with what your criteria actually
need — these are a shape, not a set.

A scenario carries **either** of these:

    "texts"   a list of strings. Each is sent as {"text": ..., "creator_id": ...}
              with a creator_id made up for you. Use this for most criteria.

    "bodies"  a list of whole request bodies, sent exactly as written. Use this
              when the malformed request IS the point — empty text, no `text`
              field at all, something enormous. A bad-input criterion needs it,
              because you cannot express "the field is missing" as a string.
"""

from eval_texts import AI_TEXTS, HUMAN_TEXTS

HUMAN = [text for _, text in HUMAN_TEXTS]   # H01-H10, supplied by me as human-written
AI = [text for _, text in AI_TEXTS]         # A01-A05, generated by Claude

# run_eval.py builds each creator_id from the first 12 characters of the scenario
# name, so the names below differ in those 12 characters. Two scenarios with the
# same start would share a creator_id and count against the same rate limit.

SCENARIOS = [
    {
        # Criterion 1: at most 1 of these 10 may come back labeled "ai".
        "name": "false positives",
        "criterion": 1,
        "texts": HUMAN,
    },
    {
        # Criterion 2: each of these must return 400 and leave one rejection
        # entry in the log. Whole request bodies, because "no text field" and
        # "text is a number" cannot be written as a string.
        "name": "bad input",
        "criterion": 2,
        "bodies": [
            {"creator_id": "eval_bad_missing"},                                # no text field
            {"text": "", "creator_id": "eval_bad_empty"},                      # empty text
            {"text": 12345, "creator_id": "eval_bad_number"},                  # not a string
            {"text": " ".join(["word"] * 44), "creator_id": "eval_bad_short"},   # 44 words
            {"text": " ".join(["word"] * 301), "creator_id": "eval_bad_long"},   # 301 words
        ],
    },
    {
        # Criterion 3: all three labels must appear at least once. One input
        # per band, picked from a preview of where each text scores: an AI text
        # (A04, about 0.91), a borderline human text (H01, about 0.52), and a
        # human text that scores low (H06, about 0.19).
        "name": "label coverage",
        "criterion": 3,
        "texts": [AI[3], HUMAN[0], HUMAN[5]],
    },
    {
        # Criterion 4: "appeal": True makes run_eval.py submit each text, appeal
        # the content_id that comes back, and read the log. A list of texts
        # alone can't express that. It also appeals one id that doesn't exist.
        "name": "appeal path",
        "criterion": 4,
        "appeal": True,
        "texts": HUMAN[:5],
    },

    {
        # Criterion 5, AI side: the first five AI texts.
        "name": "ai spread",
        "criterion": 5,
        "texts": AI[:5],
    },
    {
        # Criterion 5, human side: the first five human texts, taken in order
        # rather than chosen for how they score.
        "name": "human spread",
        "criterion": 5,
        "texts": HUMAN[:5],
    },
]


def validate() -> list[str]:
    """
    Complain about anything malformed, before a long run rather than during.

    A "bodies" scenario is deliberately exempt from the empty check — an empty
    string is the whole point of a bad-input case, and refusing to run one
    would make that criterion untestable.
    """
    problems = []
    for i, scenario in enumerate(SCENARIOS, 1):
        if not scenario.get("name"):
            problems.append(f"scenario {i} has no name")

        texts = scenario.get("texts")
        bodies = scenario.get("bodies")

        if texts and bodies:
            problems.append(
                f"scenario {i} ('{scenario.get('name')}') has both texts and "
                f"bodies — pick one"
            )
            continue

        if bodies:
            for j, body in enumerate(bodies, 1):
                if not isinstance(body, dict):
                    problems.append(
                        f"scenario {i}, body {j} is not a dict — bodies are whole "
                        f"request bodies, like {{'text': '', 'creator_id': 'x'}}"
                    )
            continue

        if not texts:
            problems.append(f"scenario {i} has no texts and no bodies")
            continue

        for j, text in enumerate(texts, 1):
            if not str(text).strip():
                problems.append(
                    f"scenario {i}, text {j} is empty — if an empty submission is what "
                    f"you're testing, use 'bodies' instead of 'texts'"
                )
            elif str(text).startswith("REPLACE ME"):
                problems.append(
                    f"scenario {i} ('{scenario.get('name')}'), text {j} is still "
                    f"the placeholder"
                )
    return problems
